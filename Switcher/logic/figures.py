class BoardFigure:
    def __init__(self, name, x, y, color, variation):
        self.name = name
        self.x = x
        self.y = y
        self.color = color
        self.cells = figure_cells(variation, x, y)

    def __str__(self):
        return f"Figure {self.name} at position ({self.x}, {self.y}) with color {self.color}"


